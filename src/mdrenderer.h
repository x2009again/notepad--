// ============================================================
// mdrenderer.h —— Markdown -> HTML 渲染器
//
// 定位：给 ndd 预览窗口用的自包含渲染器。
// 不依赖任何第三方库（md4c / marked / discmark 等），
// 全部在Qt 内做，避免额外DLL 与部署复杂度。
//
// 已覆盖语法：
//   ATX 标题 # ~######、Setext 标题（=== / ---）
//   段落、硬换行（行尾两空格 / 反斜杠）
//   无序列表 - * +、有序列表 1.、任务列表 - [ ] / - [x]
//   嵌套列表（按缩进递归）、引用块 >（可嵌套）
//   围栏代码块 ``` / ~~~（含语言标注）
//   缩进式代码块（4 空格）
//   GFM 表格（含 :---: 对齐、行内转义竖线）
//   水平分割线 --- *** ___
//   行内：**粗体** *斜体* ***粗斜体*** `行内码`
//         ~~删除线~~ [文本](链接) ![图片](链接)
//         自动链接（尖括号包裹的地址）与裸 URL
//   反转义 \` \* \_ 等
//   HTML 实体透传
// ============================================================

#pragma once

#include <QString>
#include <QStringList>

namespace MdRenderer {

// 把 Markdown 文本渲染为 HTML 片段（不含 <html><head>）。
QString renderToHtml(const QString& markdown);

} // namespace MdRenderer